const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const sql=fs.readFileSync(path.join(root,'supabase/yamaportal-platform-roles.sql'),'utf8');
const dependencies=fs.readFileSync(path.join(root,'supabase/yamaportal-role-permission-dependencies.sql'),'utf8');
const accountAudit=fs.readFileSync(path.join(root,'supabase/yamaportal-user-audit-account-actions.sql'),'utf8');
const edge=fs.readFileSync(path.join(root,'supabase/functions/yamachat-snapshot-v11/index.ts'),'utf8');
const ui=fs.readFileSync(path.join(root,'products/yamaportal/preview/dist/admin-ui.js'),'utf8');
assert.match(sql,/role in \('ADMIN', 'MODERATOR', 'USER'\)/,'The current superadmin remains outside assignable roles');
assert.match(sql,/private\.service_is_platform_owner\(p_actor_user_id\)/,'Role assignment must require the existing owner');
assert.match(sql,/The owner role cannot be changed here/,'Owner identity cannot be overwritten from role tools');
assert.match(sql,/platform_role_audit/,'Role changes must be audited');
assert.match(sql,/revoke all on function public\.service_set_platform_role[\s\S]*?grant execute on function public\.service_set_platform_role[\s\S]*?service_role/i,'Only the server service role may write platform roles');
assert.match(dependencies,/storage_delete_requires_read/,'Storage deletion requires metadata read access');
assert.match(dependencies,/users_suspend_requires_read/,'Account suspension requires user-list access');
assert.match(edge,/'storage-summary': 'storage\.read'/);
assert.match(edge,/'storage-delete': 'storage\.delete'/);
assert.match(edge,/list: 'users\.read'/);
