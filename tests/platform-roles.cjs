assert(unbanAt>=0&&unbanAt<unbanMutationAt,'An unban must be durably audit-started before changing Auth');
assert.match(accountActions,/Zadej důvod zrušení pozastavení/);
assert.match(ui,/data-user-role-select/);
assert.match(ui,/data-role-permission/);
assert.match(ui,/data-user-reset/);
assert.match(ui,/data-user-audit/);
assert.match(ui,/invoke\(sb,'user-audit'/);
assert.match(ui,/role-audit/);
assert.match(ui,/access-status/);
console.log('PASS Platform roles are owner-managed, permission-scoped, server-checked, audited, and exposed through the admin UI.');
