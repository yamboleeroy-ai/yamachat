const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'../products/yamaportal/preview/dist/admin-ui.js'),'utf8');
const listeners={};
let allowed=true,signedIn=true;
const client={auth:{getUser:async()=>({data:{user:{id:'owner-id'}},error:null})},functions:{invoke:async(name,{body})=>{assert.equal(name,'yamachat-snapshot-v11');if(body.action==='access-status')return {data:{ok:true,is_owner:allowed,role:allowed?'OWNER':'USER',permissions:[]},error:null};return {data:{ok:true},error:null}}}};
const sandbox={window:{YamaAccountUI:{isSignedIn:()=>signedIn},YamaPortalIntegration:{sharedClient:()=>client},dispatchEvent(){}},document:{addEventListener:(name,callback)=>{listeners[name]=callback}},location:{origin:'https://portal.example'},Event,FormData:function(){}};
vm.runInNewContext(source,sandbox);
(async()=>{
  await sandbox.window.YamaAdminUI.init();
  assert.equal(sandbox.window.YamaAdminUI.isAdmin(),true,'server-verified platform owner is allowed');
  allowed=false;
  await sandbox.window.YamaAdminUI.init();
  assert.equal(sandbox.window.YamaAdminUI.isAdmin(),false,'a non-admin response removes the owner entry');
  signedIn=false;allowed=true;
  const pending=sandbox.window.YamaAdminUI.init();
  signedIn=true;
  await sandbox.window.YamaAdminUI.init();
  await pending;
  await new Promise(resolve=>setImmediate(resolve));
  assert.equal(sandbox.window.YamaAdminUI.isAdmin(),true,'a sign-in arriving during initial role lookup is retried');
  assert.match(source,/invoke\(sb,'access-status'\)/);
  assert.match(source,/name="confirm" required/);
  assert.match(source,/functions\.invoke\('yamachat-snapshot-v11'/);
  assert.match(source,/invoke\(sb,'list'/);
  assert.match(source,/data-storage-refresh/);
  assert.match(source,/invoke\(sb,'storage-delete'/);
  assert.match(source,/confirm_path:typed/);
  assert.match(source,/data-user-action="ban"/);
  assert.match(source,/data-user-action="unban"/);
  assert.match(source,/await invoke\(sb,'ban'/);
  assert.match(source,/await invoke\(sb,'unban'/);
  assert.match(source,/Zadej důvod pozastavení účtu/);
  assert.match(source,/invoke\(sb,'role-list'/);
  assert.match(source,/invoke\(sb,'role-set'/);
  assert.match(source,/data-role-audit/);
  assert.match(source,/invoke\(sb,'reset-password'/);
  assert.match(source,/data-user-reset/);
  assert.match(source,/data-host-list/);
  assert.match(source,/admin\/user-servers/);
  assert.match(source,/admin\/server-action/);
  assert.match(source,/Zadej důvod této správcovské akce/);
  assert.match(source,/operation,reason:reason\.trim\(\)/);
  assert.match(source,/Bezpečně vypnout/);
  assert.match(source,/Restartovat/);
  assert.doesNotMatch(source,/admin\/server-delete/);
  assert.match(source,/Rozumím, že tato zpráva bude odeslána všem uživatelům Yamachat/);
  assert.match(source,/if\(!values\.get\('confirm'\)\)/);
  assert.match(source,/from\('account_messages'\)\.insert\(recipients\.map/);
  assert.match(source,/created_by:user\.id/);
  assert.doesNotMatch(source,/service_role|serviceRole|sb_secret_/i);
  console.log('PASS: owner UI requires the server admin check and announcement publishing uses RLS-bound user sessions.');
})().catch(error=>{console.error(error);process.exitCode=1;});
